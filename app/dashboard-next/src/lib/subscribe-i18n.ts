export function detectSubLang(): SubLang {
  if (typeof window === "undefined") return "fa";
  const q = new URLSearchParams(window.location.search).get("lang");
  if (q === "fa" || q === "ru" || q === "zh" || q === "en") return q;
  try {
    const saved = localStorage.getItem("nx_sub_lang");
    if (saved === "fa" || saved === "ru" || saved === "zh" || saved === "en") {
      return saved as SubLang;
    }
  } catch {
    /* ignore */
  }
  // Default Persian regardless of browser locale.
  return "fa";
}

export function rememberSubLang(code: SubLang): void {
  try {
    localStorage.setItem("nx_sub_lang", code);
  } catch {
    /* ignore */
  }
}

export function t(lang: SubLang, key: string): string {
  return MESSAGES[lang][key] ?? MESSAGES.en[key] ?? key;
}

