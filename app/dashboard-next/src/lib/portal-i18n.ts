export const PORTAL_LANGS: { code: PortalLang; label: string }[] = [
  { code: "fa", label: "فارسی" },
  { code: "en", label: "English" },
  { code: "ru", label: "Русский" },
  { code: "zh", label: "中文" },
];

const LANG_KEY = "nx_portal_lang";

function isPortalLang(value: string | null): value is PortalLang {
  return value === "fa" || value === "en" || value === "ru" || value === "zh";
}

/** Remember the picked language so an installed PWA reopens in it. */
export function storePortalLang(lang: PortalLang): void {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* private mode */
  }
}

export function detectPortalLang(): PortalLang {
  if (typeof window === "undefined") return "fa";
  const q = new URLSearchParams(window.location.search).get("lang");
  if (isPortalLang(q)) return q;
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (isPortalLang(saved)) return saved;
  } catch {
    /* private mode */
  }
  const lang = (navigator.language || "").toLowerCase();
  if (lang.startsWith("fa")) return "fa";
  if (lang.startsWith("ru")) return "ru";
  if (lang.startsWith("zh")) return "zh";
  return "en";
}

export function pt(lang: PortalLang, key: string): string {
  return STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
}
